import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { config } from '../config.js';

/**
 * B 站 Cookie 处理。
 *
 * yt-dlp 的 --add-header Cookie:... 会把 Cookie 的作用域限定到下载 URL 的域名
 * （.www.bilibili.com），导致 api.bilibili.com 的清晰度 / 字幕接口拿不到 SESSDATA。
 * 因此这里把用户粘贴的 Cookie 串写成 Netscape cookies.txt，域固定为 .bilibili.com，
 * 再通过 --cookies 传给 yt-dlp。
 */
const COOKIE_DOMAIN = '.bilibili.com';
const COOKIE_FILE_NAME = 'cookies.txt';

const ATTRIBUTES = new Set([
  'domain',
  'path',
  'expires',
  'max-age',
  'secure',
  'httponly',
  'samesite',
  'priority',
  'partitioned',
]);

const COOKIE_NAME = /^[!#$%&'*+\-.^_`|~0-9A-Za-z]+$/;
const MAX_COOKIE_FILE_BYTES = 512 * 1024;

export interface CookiePair {
  name: string;
  value: string;
}

/**
 * 允许 Cookie 输入框直接填文件路径（如浏览器导出的 cookies.txt）。
 * 只对单行、无 Cookie 语法的输入尝试读文件，避免误读普通 Cookie 值。
 */
function loadCookieInput(raw: string): string {
  const input = raw.trim();
  if (!input || /[\r\n\t;=]/.test(input)) return input;
  try {
    const stat = fs.statSync(input);
    if (!stat.isFile() || stat.size > MAX_COOKIE_FILE_BYTES) return input;
    return fs.readFileSync(input, 'utf8').trim();
  } catch {
    return input;
  }
}

function cleanValue(value: string): string {
  return value.replace(/[\r\n]/g, '').trim();
}

function pushPair(pairs: CookiePair[], seen: Set<string>, name: string, value: string): void {
  const key = name.trim();
  const val = cleanValue(value);
  if (!key || !COOKIE_NAME.test(key) || ATTRIBUTES.has(key.toLowerCase())) return;
  if (val.length > 8192) return;
  if (seen.has(key)) return;
  seen.add(key);
  pairs.push({ name: key, value: val });
}

/**
 * 接受三种输入：
 * 1. 完整 Cookie 头：`SESSDATA=...; bili_jct=...; buvid3=...`
 * 2. 只粘贴 SESSDATA 的值（没有 `=`）
 * 3. Netscape cookies.txt 的一行或多行
 * 4. 上述任意一种所在的文件路径
 */
export function parseCookiePairs(raw: string): CookiePair[] {
  const input = loadCookieInput(raw);
  if (!input) return [];

  const pairs: CookiePair[] = [];
  const seen = new Set<string>();
  const body = input.replace(/^cookie:\s*/i, '');

  if (body.includes('\t')) {
    for (const rawLine of body.split(/\r?\n/)) {
      if (!rawLine.trim()) continue;
      // Netscape 导出会把 HttpOnly Cookie 写成 #HttpOnly_ 前缀，不能当注释丢掉
      let line = rawLine;
      if (line.startsWith('#HttpOnly_')) line = line.slice('#HttpOnly_'.length);
      else if (line.trimStart().startsWith('#')) continue;
      const fields = line.split('\t');
      if (fields.length < 7) continue;
      const domain = fields[0].trim().toLowerCase();
      if (!domain.endsWith('bilibili.com')) continue;
      pushPair(pairs, seen, fields[5], fields[6]);
    }
    if (pairs.length > 0) return pairs;
  }

  if (!body.includes('=')) {
    pushPair(pairs, seen, 'SESSDATA', body);
    return pairs;
  }

  for (const chunk of body.split(/[;\r\n]+/)) {
    const part = chunk.trim();
    if (!part) continue;
    const index = part.indexOf('=');
    if (index <= 0) continue;
    pushPair(pairs, seen, part.slice(0, index), part.slice(index + 1));
  }
  return pairs;
}

/** 给 fetch 用的 Cookie 请求头；过滤掉 Domain/Path 等属性 */
export function cookieHeader(raw: string): string | null {
  const pairs = parseCookiePairs(raw);
  if (pairs.length === 0) return null;
  return pairs.map((pair) => `${pair.name}=${pair.value}`).join('; ');
}

export function cookieFilePath(): string {
  return path.join(config.dataDir, COOKIE_FILE_NAME);
}

/**
 * 写入 Netscape cookies.txt；Cookie 为空时删除旧文件。
 * 返回文件路径，没有 Cookie 时返回 null。
 */
function writeCookieFileTo(raw: string, file: string): string | null {
  const pairs = parseCookiePairs(raw);

  if (pairs.length === 0) {
    fs.rmSync(file, { force: true });
    return null;
  }

  const lines = [
    '# Netscape HTTP Cookie File',
    '# Generated by BiliFlow. Contains login credentials; do not commit or share.',
    '',
    ...pairs.map((pair) =>
      [COOKIE_DOMAIN, 'TRUE', '/', 'FALSE', '0', pair.name, pair.value].join('\t'),
    ),
    '',
  ];

  fs.mkdirSync(path.dirname(file), { recursive: true });
  const temp = `${file}.${process.pid}.${randomUUID()}.tmp`;
  fs.writeFileSync(temp, lines.join('\n'), { encoding: 'utf8', mode: 0o600 });
  try {
    fs.renameSync(temp, file);
  } catch {
    // Windows 上目标文件被占用时 rename 可能失败，退化为覆盖写
    fs.rmSync(file, { force: true });
    fs.renameSync(temp, file);
  }
  return file;
}

function batchCookieFile(batchId: string): string {
  const safe = batchId.replace(/[^A-Za-z0-9_-]/g, '') || randomUUID();
  return path.join(config.dataDir, 'batch-cookies', `${safe}.txt`);
}

/** 持久设置里的 B 站 Cookie，固定写入 data/cookies.txt */
export function writeCookieFile(raw: string): string | null {
  return writeCookieFileTo(raw, cookieFilePath());
}

/**
 * 主界面填写的 Cookie 按批次落盘，避免覆盖设置里的登录信息。
 * 文件在批次删除 / 清空已完成时清理。
 */
export function writeBatchCookieFile(raw: string, batchId: string): string | null {
  const file = batchCookieFile(batchId);
  try {
    if (fs.statSync(file).size > 0) return file;
  } catch {
    /* 文件不存在时写入 */
  }
  return writeCookieFileTo(raw, file);
}

/** 预览用的临时 Cookie 文件，调用方负责在结束后删除 */
export function writeTempCookieFile(raw: string): string | null {
  return writeCookieFileTo(raw, path.join(config.dataDir, 'batch-cookies', `preview-${randomUUID()}.txt`));
}

export function removeCookieFile(file: string | null | undefined): void {
  if (!file) return;
  try {
    fs.rmSync(file, { force: true });
  } catch {
    /* 文件可能仍被 yt-dlp 占用，启动时会统一清理 */
  }
}

export function removeBatchCookieFile(batchId: string): void {
  try {
    fs.rmSync(batchCookieFile(batchId), { force: true });
  } catch {
    /* 文件可能仍被 yt-dlp 占用 */
  }
}

/** 服务启动时清理上一轮遗留的批次 Cookie（批次 Cookie 只存在于内存映射中） */
export function clearBatchCookieFiles(): void {
  try {
    fs.rmSync(path.join(config.dataDir, 'batch-cookies'), { recursive: true, force: true });
  } catch {
    /* 占用中的文件留给下次启动清理 */
  }
}

/**
 * 确保 cookies.txt 存在（服务启动、手动改过 state.json 等场景）。
 * 返回可用于 --cookies 的路径。
 */
export function ensureCookieFile(raw: string): string | null {
  const pairs = parseCookiePairs(raw);
  if (pairs.length === 0) return null;
  const file = cookieFilePath();
  if (!fs.existsSync(file)) writeCookieFile(raw);
  return file;
}
